# ---------------------------------------------------------------------------
# 4.  BUILD LOOKUP TABLE  (lowercase canonical → entry)
# ---------------------------------------------------------------------------

SKILL_LOOKUP: Dict[str, dict] = {}

for _name, (_cat, _weight) in RAW_SKILLS.items():
    SKILL_LOOKUP[_name.lower()] = {
        "name":     _name,
        "category": _cat,
        "weight":   _weight,
    }

# Alias lookup (lowercase alias → canonical lowercase for SKILL_LOOKUP)
ALIAS_TO_CANONICAL: Dict[str, str] = {
    alias.lower(): canonical.lower()
    for alias, canonical in ALIASES.items()
}


def resolve_skill(token: str) -> dict | None:
    """
    Resolve a raw token to a canonical skill entry.
    Returns None if no match found.
    Checks: exact → alias → None
    """
    t = token.strip().lower()
    if t in SKILL_LOOKUP:
        return SKILL_LOOKUP[t]
    if t in ALIAS_TO_CANONICAL:
        canonical = ALIAS_TO_CANONICAL[t]
        return SKILL_LOOKUP.get(canonical)
    return None


def get_all_canonical_names() -> Set[str]:
    """Return a set of all canonical skill display names."""
    return {v["name"] for v in SKILL_LOOKUP.values()}


def get_skills_by_category(category: str) -> List[str]:
    """Return canonical names for a given category."""
    return [v["name"] for v in SKILL_LOOKUP.values() if v["category"] == category]
